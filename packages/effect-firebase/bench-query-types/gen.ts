/**
 * THROWAWAY (#126). Generates a synthetic model and the same queries in each
 * style, at one scale.
 *
 *   vpx bench-query-types/gen.ts <name> <width> <depth> <models> <queriesPerSource>
 *
 * A struct at each level has `width` fields cycling through the kinds below,
 * every third one a nested `FirestoreModel.Struct` until `depth`, and the
 * last one a `FirestoreModel.Record` of structs. Odd models rotate the kinds,
 * so a group of an even and an odd model shares only the common fields.
 */
import * as fs from "node:fs";
import * as path from "node:path";

const [name, width, depth, models, perSource] = process.argv.slice(2);
const W = Number(width);
const D = Number(depth);
const M = Number(models);
const Q = Number(perSource);

interface Kind {
  readonly schema: string;
  readonly op: "==" | ">" | ">=" | "array-contains";
  readonly value: string;
}
const kinds: ReadonlyArray<Kind> = [
  { schema: "Schema.String", op: ">=", value: `"x"` },
  { schema: "Schema.Finite", op: ">", value: "1" },
  { schema: "Schema.Boolean", op: "==", value: "true" },
  { schema: "Schema.BigInt", op: "==", value: "1n" },
  { schema: "Schema.Array(Schema.String)", op: "array-contains", value: `"x"` },
  { schema: "FirestoreModel.Timestamp(Schema.Date)", op: ">", value: "new Date(0)" },
  { schema: "FirestoreModel.Record(Schema.String, Schema.String)", op: "==", value: `"x"` },
  { schema: "FirestoreModel.Optional(Schema.Finite)", op: ">=", value: "1" },
];
const RECORD = 6;

interface Leaf {
  readonly segments: ReadonlyArray<string>; // "*" is a record key
  readonly kind: Kind;
}

const struct = (
  level: number,
  seed: number,
  prefix: ReadonlyArray<string>,
  leaves: Array<Leaf>,
): string => {
  const fields: Array<string> = [];
  for (let j = 0; j < W; j++) {
    const key = `f${j}`;
    const at = [...prefix, key];
    if (level < D && j === W - 1) {
      fields.push(
        `${key}: FirestoreModel.Record(Schema.String, FirestoreModel.Struct({${struct(level + 1, seed, [...at, "*"], leaves)}}))`,
      );
    } else if (level < D && j % 3 === 2) {
      fields.push(`${key}: FirestoreModel.Struct({${struct(level + 1, seed, at, leaves)}})`);
    } else {
      const k = (j + seed) % kinds.length;
      fields.push(`${key}: ${kinds[k]!.schema}`);
      leaves.push({ segments: k === RECORD ? [...at, "*"] : at, kind: kinds[k]! });
    }
  }
  return fields.join(", ");
};

const common = `likes: Schema.Finite, title: Schema.String, meta: FirestoreModel.Struct({ createdAt: FirestoreModel.Timestamp(Schema.Date), likes: Schema.Finite })`;
const commonLeaves: ReadonlyArray<Leaf> = [
  { segments: ["likes"], kind: kinds[1]! },
  { segments: ["title"], kind: kinds[0]! },
  { segments: ["meta", "createdAt"], kind: kinds[5]! },
  { segments: ["meta", "likes"], kind: kinds[1]! },
];

const leavesBySeed: Array<Array<Leaf>> = [[], []];
const trees = [0, 1].map((seed) => struct(1, seed, [], leavesBySeed[seed]!));
for (const ls of leavesBySeed) ls.push(...commonLeaves);

let model = `// GENERATED by gen.ts (${name}: width ${W}, depth ${D}, models ${M}). Do not edit.
import * as Collection from "@visiolab/effect-firebase/firestore/Collection";
import * as CollectionGroup from "@visiolab/effect-firebase/firestore/CollectionGroup";
import * as FirestoreModel from "@visiolab/effect-firebase/firestore/FirestoreModel";
import { Schema } from "effect";

`;
for (let i = 0; i < M; i++) {
  model += `export class Model${i} extends FirestoreModel.Class<Model${i}>("Model${i}")({ ${common}, ${trees[i % 2]} }) {}\n`;
  model += `export const C${i} = Collection.make("c${i}", Model${i});\n`;
}
for (let v = 1; v <= 3; v++) {
  model += `export class V${v} extends FirestoreModel.Class<V${v}>("V${v}")({ v: Schema.Literal(${v}), only${v}: Schema.String, ${common}, ${trees[0]} }) {}\n`;
}
model += `export const Versions = Collection.make("versions", FirestoreModel.Union([V1, V2, V3]));\n`;
for (let k = 0; k < 4; k++) {
  model += `const P${k} = Collection.make("p${k}", Model0);\n`;
}
model += `export const Items = CollectionGroup.make(${[0, 1, 2, 3].map((k) => `P${k}.subcollection("items", Model0)`).join(", ")});\n`;
model += `export const MixedItems = CollectionGroup.make(P0.subcollection("mixed", Model0), P1.subcollection("mixed", Model1));\n`;

// Sources: every collection, the union document, the group, the mixed group.
interface Src {
  readonly def: string;
  readonly ref: string;
  readonly leaves: ReadonlyArray<Leaf>;
}
const sources: Array<Src> = [];
for (let i = 0; i < M; i++)
  sources.push({ def: `M.C${i}`, ref: `M.C${i}.collection()`, leaves: leavesBySeed[i % 2]! });
sources.push({ def: "M.Versions", ref: "M.Versions.collection()", leaves: leavesBySeed[0]! });
sources.push({ def: "M.Items", ref: "M.Items", leaves: leavesBySeed[0]! });
sources.push({ def: "M.MixedItems", ref: "M.MixedItems", leaves: commonLeaves });

// Spread the queries over the leaves, deepest first, so every depth is read.
const pick = (ls: ReadonlyArray<Leaf>, n: number): Leaf => {
  const sorted = [...ls].sort((a, b) => b.segments.length - a.segments.length);
  return sorted[(n * 7) % sorted.length]!;
};
const dotted = (l: Leaf) => l.segments.map((s) => (s === "*" ? "k" : s)).join(".");
const access = (l: Leaf) => l.segments.map((s) => (s === "*" ? `["k"]` : `.${s}`)).join("");
const fieldOp = { "==": "eq", ">": "gt", ">=": "gte", "array-contains": "arrayContains" } as const;

let dottedSrc = `// GENERATED. Dotted paths, flattened map.\nimport { pipe } from "effect";\nimport * as Q from "../../lib/dotted.ts";\nimport * as M from "./model.ts";\n\n`;
let lookupSrc = dottedSrc
  .replace("flattened map", "per-call lookup")
  .replace("lib/dotted.ts", "lib/dottedLookup.ts");
let fieldsSrc = `// GENERATED. Field objects.\nimport { pipe } from "effect";\nimport * as F from "../../lib/fields.ts";\nimport * as M from "./model.ts";\n\n`;
let updateSrc = `// GENERATED. The existing UpdatePaths, on the same model, for reference.\nimport type * as M from "./model.ts";\n\n`;
const baselineSrc = `// GENERATED. The model alone.\nimport * as M from "./model.ts";\n\n${sources.map((s, i) => `export const s${i} = ${s.ref};`).join("\n")}\n`;

sources.forEach((s, si) => {
  fieldsSrc += `const p${si} = F.fields(${s.def});\n`;
  for (let q = 0; q < Q; q++) {
    const a = pick(s.leaves, si * Q + q * 2);
    const b = pick(s.leaves, si * Q + q * 2 + 1);
    dottedSrc += `export const q${si}_${q} = pipe(${s.ref}, Q.where("${dotted(a)}", "${a.kind.op}", ${a.kind.value}), Q.where("${dotted(b)}", "${b.kind.op}", ${b.kind.value}), Q.orderBy("meta.likes", "desc"));\n`;
    lookupSrc += `export const q${si}_${q} = pipe(${s.ref}, Q.where("${dotted(a)}", "${a.kind.op}", ${a.kind.value}), Q.where("${dotted(b)}", "${b.kind.op}", ${b.kind.value}), Q.orderBy("meta.likes", "desc"));\n`;
    fieldsSrc += `export const q${si}_${q} = pipe(${s.ref}, F.where(F.and(F.${fieldOp[a.kind.op]}(p${si}${access(a)}, ${a.kind.value}), F.${fieldOp[b.kind.op]}(p${si}${access(b)}, ${b.kind.value}))), F.orderBy(F.desc(p${si}.meta.likes)));\n`;
  }
});
// What each style must refuse, so a cheap check is not an `any` leaking through.
const bigintPath = leavesBySeed[0]!.find((l) => l.kind.schema === "Schema.BigInt")!;
const negDotted = `
// @ts-expect-error unknown path
void pipe(M.C0.collection(), Q.where("nope", "==", 1));
// @ts-expect-error wrong value Type
void pipe(M.C0.collection(), Q.where("likes", "==", "1"));
// @ts-expect-error bigint is not orderable
void pipe(M.C0.collection(), Q.where("${dotted(bigintPath)}", ">", 1n));
// @ts-expect-error not a Shared Field of the mixed group
void pipe(M.MixedItems, Q.where("f0", "==", "x"));
`;
dottedSrc += negDotted;
lookupSrc += negDotted;
fieldsSrc += `
// @ts-expect-error unknown field
void p0.nope;
// @ts-expect-error wrong value Type
void F.eq(p0.likes, "1");
// @ts-expect-error bigint is not orderable
void F.gt(p0${access(bigintPath)}, 1n);
// @ts-expect-error not a Shared Field of the mixed group
void p${sources.length - 1}.f0;
// @ts-expect-error a filter from another collection
void pipe(M.C1.collection(), F.where(F.eq(p0.likes, 1)));
`;

for (let i = 0; i < M; i++) {
  const deep = dotted(pick(leavesBySeed[i % 2]!, 0));
  updateSrc += `export const u${i}: ReadonlyArray<keyof (typeof M.Model${i}.update)["Encoded"]> = ["likes", "${deep}"];\n`;
  updateSrc += `// @ts-expect-error unknown path\nexport const n${i}: keyof (typeof M.Model${i}.update)["Encoded"] = "nope";\n`;
}

const out = path.join(import.meta.dirname, "generated", name!);
fs.mkdirSync(out, { recursive: true });
const write = (f: string, s: string) => fs.writeFileSync(path.join(out, f), s);
write("model.ts", model);
write("baseline.ts", baselineSrc);
write("dotted.ts", dottedSrc);
write("dottedLookup.ts", lookupSrc);
write("fields.ts", fieldsSrc);
write("update.ts", updateSrc);
// One query on a collection and one on the union document: what an editor re-checks after an edit.
const one = (src: string, header: number) => {
  const lines = src.split("\n");
  return (
    [
      ...lines.slice(0, header),
      ...lines.filter(
        (l) => l.startsWith("export const q0_0 ") || l.startsWith(`export const q${M}_0 `),
      ),
    ].join("\n") + "\n"
  );
};
write(
  "baseline1.ts",
  `import * as M from "./model.ts";\n\nexport const a = M.C0.collection();\nexport const b = M.Versions.collection();\n`,
);
write("dotted1.ts", one(dottedSrc, 5));
write("dottedLookup1.ts", one(lookupSrc, 5));
write(
  "fields1.ts",
  one(fieldsSrc, 5).replace(
    /\n(?=export)/,
    "\n" +
      [0, M]
        .map((si) => fieldsSrc.split("\n").find((l) => l.startsWith(`const p${si} `)))
        .join("\n") +
      "\n",
  ),
);
for (const v of [
  "baseline",
  "dotted",
  "dottedLookup",
  "fields",
  "update",
  "baseline1",
  "dotted1",
  "dottedLookup1",
  "fields1",
]) {
  write(
    `tsconfig.${v}.json`,
    JSON.stringify(
      {
        extends: "../../../tsconfig.json",
        compilerOptions: { plugins: [], lib: ["es2023", "dom"] },
        files: [`./${v}.ts`],
      },
      null,
      2,
    ),
  );
}
const paths = leavesBySeed[0]!.length;
console.log(
  `${name}: ${paths} leaf paths per model, ${sources.length} sources, ${sources.length * Q} queries per style`,
);
